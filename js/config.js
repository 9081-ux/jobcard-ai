// config.js — Firebase configuration, loaded from an untracked local file.
//
// HOW IT WORKS
// 1. index.html tries to load config.local.js (git-ignored). If it exists and
//    sets window.JOBCARD_CONFIG, the app runs against real Firebase AI Logic.
// 2. Otherwise the app runs in mock mode — every feature works end to end
//    against the local mock engine, and the UI says so.
//
// NEVER commit config.local.js, .env files, App Check debug tokens, or
// service account keys. The Firebase web apiKey is a public identifier, but
// even that lives only in the untracked local file, never in this repo.

// Read lazily (called on first AI use, after every script has loaded) so
// config.local.js — a deferred classic script — is guaranteed to have run
// before we look for window.JOBCARD_CONFIG.
export function getConfig() {
  const c = typeof window !== 'undefined' ? window.JOBCARD_CONFIG : undefined;
  if (c && c.apiKey && c.projectId && c.appId) {
    return {
      mode: 'firebase',
      firebase: {
        apiKey: c.apiKey,
        authDomain: c.authDomain,
        projectId: c.projectId,
        storageBucket: c.storageBucket,
        messagingSenderId: c.messagingSenderId,
        appId: c.appId,
        // Optional: reCAPTCHA Enterprise site key for App Check.
        appCheckSiteKey: c.appCheckSiteKey || undefined,
        // Optional: a fixed, console-registered App Check debug token
        // (deployed demo). The debug provider uses this exact token string;
        // it must be registered in the Firebase console (App Check >
        // Manage debug tokens). Never commit a token — it lives only in
        // the untracked config.local.js (local or deploy copy).
        appCheckDebugToken: c.appCheckDebugToken || undefined,
        // Optional dev flag: use the App Check debug provider locally.
        // The token is generated by the browser — never paste a token here.
        appCheckDebug: c.appCheckDebug === true,
      },
    };
  }
  return { mode: 'mock' };
}
